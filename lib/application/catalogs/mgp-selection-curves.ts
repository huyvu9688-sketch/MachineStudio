export const MGP_SELECTION_CURVES: readonly MgpSelectionCurve[] = Object.freeze(
  (CURVE_SEEDS as readonly CurveSeed[]).flatMap((seed) => {
    const pressureBands = seed.pressureBands ?? [undefined];
    return seed.bearingTypes.flatMap((bearingType) =>
      pressureBands.flatMap((pressureBand) =>
        seed.boreDiametersMm.map((boreDiameterMm) => {
          const transferSpeedRangeMPerMin =
            seed.applicationCase === "stopper"
              ? Object.freeze([
                  seed.points[0]![0],
                  seed.points[seed.points.length - 1]![0],
                ] as const)
              : undefined;
          const curve: MgpSelectionCurve = {
            graph: seed.graph,
            sourcePage: seed.sourcePage,
            applicationCase: seed.applicationCase,
            bearingType,
            boreDiameterMm,
            xUnit: seed.xUnit,
            points: Object.freeze(
              seed.points.map(([x, loadMassKg]) =>
                Object.freeze({ x, loadMassKg }),
              ),
            ),
            ...(pressureBand === undefined ? {} : { pressureBand }),
            ...(seed.maxSpeedMmPerS === undefined
              ? {}
              : { maxSpeedMmPerS: seed.maxSpeedMmPerS }),
            ...(transferSpeedRangeMPerMin === undefined
              ? {}
              : { transferSpeedRangeMPerMin }),
            ...("maxStrokeMm" in seed ? { maxStrokeMm: seed.maxStrokeMm } : {}),
            ...("minStrokeExclusiveMm" in seed
              ? { minStrokeExclusiveMm: seed.minStrokeExclusiveMm }
              : {}),
            ...("horizontalOffsetMm" in seed
              ? { horizontalOffsetMm: seed.horizontalOffsetMm }
              : {}),
          };
          return Object.freeze(curve);
        }),
      ),
    );
  }),
);
export type MgpSelectionOutOfEnvelopeReason =
  | "invalid_input"
  | "unsupported_operating_pressure"
  | "piston_speed_above_published_envelope"
  | "eccentric_distance_requires_selection_software"
  | "horizontal_offset_above_published_envelope"
  | "stopper_requires_slide_bearing"
  | "stopper_bore_not_published"
  | "stopper_stroke_above_bore_limit"
  | "transfer_speed_outside_published_envelope"
  | "x_outside_curve_domain";

export interface MgpSelectionOutOfEnvelope {
  readonly inEnvelope: false;
  readonly reason: MgpSelectionOutOfEnvelopeReason;
  readonly message: string;
}

export interface MgpSelectedBand {
  readonly inEnvelope: true;
  readonly graph: number;
  readonly applicationCase: MgpApplicationCase;
  readonly bearingType: MgpBearingType;
  readonly operatingPressureMPa: number;
  readonly pressureBand?: MgpPressureBand;
  readonly maxSpeedMmPerS?: 200 | 400;
  readonly transferSpeedRangeMPerMin?: readonly [
    minimum: number,
    maximum: number,
  ];
  readonly maxStrokeMm?: 30 | 50;
  readonly minStrokeExclusiveMm?: 30 | 50;
  readonly horizontalOffsetMm?: 50 | 100;
  readonly xUnit: "mm" | "m/min";
  readonly xValue: number;
  readonly loadCoefficient?: 0.6 | 1 | 1.7;
  readonly scopeWarnings?: readonly string[];
}

export interface MgpSelectionBandInput {
  readonly applicationCase: MgpApplicationCase;
  readonly bearingType: MgpBearingType;
  readonly operatingPressureMPa: number;
  readonly requiredStrokeMm: number;
  readonly pistonSpeedMmPerS?: number;
  readonly eccentricDistanceMm?: number;
  readonly transferSpeedMPerMin?: number;
  readonly boreDiameterMm?: number;
}

export type MgpSelectionBandResult =
  MgpSelectedBand | MgpSelectionOutOfEnvelope;

function outOfEnvelope(
  reason: MgpSelectionOutOfEnvelopeReason,
  message: string,
): MgpSelectionOutOfEnvelope {
  return { inEnvelope: false, reason, message };
}

function isMgpApplicationCase(value: unknown): value is MgpApplicationCase {
  return (
    value === "vertical_lifter" ||
    value === "horizontal_pusher" ||
    value === "stopper"
  );
}

function isMgpBearingType(value: unknown): value is MgpBearingType {
  return (
    value === "slide" ||
    value === "ball_bushing" ||
    value === "high_precision_ball_bushing"
  );
}

function resolvePressureBand(
  pressureMPa: number,
): MgpPressureBand | MgpSelectionOutOfEnvelope {
  if (!Number.isFinite(pressureMPa) || pressureMPa <= 0) {
    return outOfEnvelope(
      "invalid_input",
      "Operating pressure must be finite and positive.",
    );
  }
  if (pressureMPa === 0.4) return "0.4_mpa";
  if (pressureMPa >= 0.5) return "at_least_0.5_mpa";
  return outOfEnvelope(
    "unsupported_operating_pressure",
    "MGP publishes selection bands at 0.4 MPa and at or above 0.5 MPa; interpolation between them is not permitted.",
  );
}

function resolveSpeedBand(speedMmPerS: number):
  | {
      readonly maxSpeedMmPerS: 200 | 400;
      readonly loadCoefficient: 0.6 | 1 | 1.7;
    }
  | MgpSelectionOutOfEnvelope {
  if (!Number.isFinite(speedMmPerS) || speedMmPerS <= 0) {
    return outOfEnvelope(
      "invalid_input",
      "Piston speed must be finite and positive.",
    );
  }
  if (speedMmPerS <= 200) {
    return { maxSpeedMmPerS: 200, loadCoefficient: 1 };
  }
  if (speedMmPerS <= 300) {
    return { maxSpeedMmPerS: 400, loadCoefficient: 1.7 };
  }
  if (speedMmPerS <= 400) {
    return { maxSpeedMmPerS: 400, loadCoefficient: 1 };
  }
  if (speedMmPerS <= 500) {
    return { maxSpeedMmPerS: 400, loadCoefficient: 0.6 };
  }
  return outOfEnvelope(
    "piston_speed_above_published_envelope",
    "MGP's page-545 speed coefficient table ends at 500 mm/s.",
  );
}

type MgpBandSelectionContext =
  | {
      readonly pressureBand: MgpPressureBand;
      readonly maxSpeedMmPerS: 200 | 400;
      readonly loadCoefficient: 0.6 | 1 | 1.7;
    }
  | {
      readonly transferSpeedRangeMPerMin: readonly [
        minimum: number,
        maximum: number,
      ];
    };

function selectedBand(
  input: MgpSelectionBandInput,
  selectionContext: MgpBandSelectionContext,
  graph: number,
  xUnit: "mm" | "m/min",
  xValue: number,
  options: {
    readonly maxStrokeMm?: 30 | 50;
    readonly minStrokeExclusiveMm?: 30 | 50;
    readonly horizontalOffsetMm?: 50 | 100;
    readonly scopeWarnings?: readonly string[];
  } = {},
): MgpSelectedBand {
  return {
    inEnvelope: true,
    graph,
    applicationCase: input.applicationCase,
    bearingType: input.bearingType,
    operatingPressureMPa: input.operatingPressureMPa,
    ...selectionContext,
    ...(options.maxStrokeMm === undefined
      ? {}
      : { maxStrokeMm: options.maxStrokeMm }),
    ...(options.minStrokeExclusiveMm === undefined
      ? {}
      : { minStrokeExclusiveMm: options.minStrokeExclusiveMm }),
    ...(options.horizontalOffsetMm === undefined
      ? {}
      : { horizontalOffsetMm: options.horizontalOffsetMm }),
    ...(options.scopeWarnings === undefined
      ? {}
      : { scopeWarnings: options.scopeWarnings }),
    xUnit,
    xValue,
  };
}
export function selectMgpSelectionBand(
  input: MgpSelectionBandInput,
): MgpSelectionBandResult {
  if (!isMgpApplicationCase(input.applicationCase)) {
    return outOfEnvelope(
      "invalid_input",
      "Application case must be a published MGP selection case.",
    );
  }
  if (!isMgpBearingType(input.bearingType)) {
    return outOfEnvelope(
      "invalid_input",
      "Bearing type must be a published MGP bearing type.",
    );
  }
  if (
    !Number.isFinite(input.operatingPressureMPa) ||
    input.operatingPressureMPa <= 0
  ) {
    return outOfEnvelope(
      "invalid_input",
      "Operating pressure must be finite and positive.",
    );
  }
  if (!Number.isFinite(input.requiredStrokeMm) || input.requiredStrokeMm < 0) {
    return outOfEnvelope(
      "invalid_input",
      "Required stroke must be finite and non-negative.",
    );
  }

  if (input.applicationCase === "stopper") {
    if (input.bearingType !== "slide") {
      return outOfEnvelope(
        "stopper_requires_slide_bearing",
        "The page-552 stopper plots apply to MGPM slide bearings only.",
      );
    }
    const bore = input.boreDiameterMm;
    if (
      bore === undefined ||
      ![12, 16, 20, 25, 32, 40, 50, 63, 80, 100].includes(bore)
    ) {
      return outOfEnvelope(
        "stopper_bore_not_published",
        "A published MGP stopper bore diameter is required to select its bore-group plot.",
      );
    }
    const maxStrokeMm: 30 | 50 = bore <= 25 ? 30 : 50;
    if (input.requiredStrokeMm > maxStrokeMm) {
      return outOfEnvelope(
        "stopper_stroke_above_bore_limit",
        `MGP limits this stopper bore group to ${maxStrokeMm} mm stroke.`,
      );
    }
    const graph = bore <= 25 ? 21 : 22;
    const sourceCurve = MGP_SELECTION_CURVES.find(
      (curve) =>
        curve.graph === graph &&
        curve.bearingType === "slide" &&
        curve.boreDiameterMm === bore,
    );
    const minimumTransferSpeed = sourceCurve?.points[0]?.x;
    const maximumTransferSpeed = sourceCurve?.points.at(-1)?.x;
    if (
      sourceCurve === undefined ||
      minimumTransferSpeed === undefined ||
      maximumTransferSpeed === undefined
    ) {
      return outOfEnvelope(
        "stopper_bore_not_published",
        `No seeded page-552 stopper curve is available for bore ${bore} mm.`,
      );
    }
    const transferSpeed = input.transferSpeedMPerMin;
    if (
      transferSpeed === undefined ||
      !Number.isFinite(transferSpeed) ||
      transferSpeed < minimumTransferSpeed ||
      transferSpeed > maximumTransferSpeed
    ) {
      return outOfEnvelope(
        "transfer_speed_outside_published_envelope",
        `The page-552 stopper curve for bore ${bore} mm covers transfer speeds from ${minimumTransferSpeed} to ${maximumTransferSpeed} m/min.`,
      );
    }
    return selectedBand(
      input,
      {
        transferSpeedRangeMPerMin: Object.freeze([
          minimumTransferSpeed,
          maximumTransferSpeed,
        ] as const),
      },
      graph,
      "m/min",
      transferSpeed,
      { maxStrokeMm, scopeWarnings: MGP_STOPPER_SCOPE_WARNINGS },
    );
  }

  const pressureBand = resolvePressureBand(input.operatingPressureMPa);
  if (typeof pressureBand !== "string") return pressureBand;

  const pistonSpeed = input.pistonSpeedMmPerS;
  if (pistonSpeed === undefined) {
    return outOfEnvelope(
      "invalid_input",
      "Piston speed is required for lifter and pusher selection.",
    );
  }
  const speed = resolveSpeedBand(pistonSpeed);
  if ("inEnvelope" in speed) return speed;

  const eccentricDistance = input.eccentricDistanceMm;
  if (
    eccentricDistance === undefined ||
    !Number.isFinite(eccentricDistance) ||
    eccentricDistance < 0
  ) {
    return outOfEnvelope(
      "invalid_input",
      "Eccentric distance must be finite and non-negative.",
    );
  }

  if (input.applicationCase === "vertical_lifter") {
    if (eccentricDistance >= 200) {
      return outOfEnvelope(
        "eccentric_distance_requires_selection_software",
        "MGP directs L at or above 200 mm to the Guide Cylinder Selection Software.",
      );
    }

    let graph: number;
    let strokeBand:
      | { readonly maxStrokeMm: 30 | 50 }
      | { readonly minStrokeExclusiveMm: 30 | 50 };
    if (input.bearingType === "slide") {
      const atMostPublishedBoundary = input.requiredStrokeMm <= 50;
      graph =
        speed.maxSpeedMmPerS === 200
          ? atMostPublishedBoundary
            ? 1
            : 2
          : atMostPublishedBoundary
            ? 3
            : 4;
      strokeBand = atMostPublishedBoundary
        ? { maxStrokeMm: 50 }
        : { minStrokeExclusiveMm: 50 };
    } else {
      const smallBoreGroup =
        input.boreDiameterMm === undefined || input.boreDiameterMm <= 25;
      const strokeBoundaryMm: 30 | 50 = smallBoreGroup ? 30 : 50;
      const atMostPublishedBoundary =
        input.requiredStrokeMm <= strokeBoundaryMm;
      const base = speed.maxSpeedMmPerS === 200 ? 5 : 9;
      graph =
        base + (smallBoreGroup ? 0 : 2) + (atMostPublishedBoundary ? 0 : 1);
      strokeBand = atMostPublishedBoundary
        ? { maxStrokeMm: strokeBoundaryMm }
        : { minStrokeExclusiveMm: strokeBoundaryMm };
    }
    return selectedBand(
      input,
      {
        pressureBand,
        maxSpeedMmPerS: speed.maxSpeedMmPerS,
        loadCoefficient: speed.loadCoefficient,
      },
      graph,
      "mm",
      eccentricDistance,
      strokeBand,
    );
  }

  if (eccentricDistance > 100) {
    return outOfEnvelope(
      "horizontal_offset_above_published_envelope",
      "MGP publishes horizontal pusher plots only for L = 50 mm and L = 100 mm.",
    );
  }
  const horizontalOffsetMm: 50 | 100 = eccentricDistance <= 50 ? 50 : 100;
  const slide = input.bearingType === "slide";
  const base =
    speed.maxSpeedMmPerS === 200 ? (slide ? 13 : 17) : slide ? 15 : 19;
  const graph = base + (horizontalOffsetMm === 50 ? 0 : 1);
  return selectedBand(
    input,
    {
      pressureBand,
      maxSpeedMmPerS: speed.maxSpeedMmPerS,
      loadCoefficient: speed.loadCoefficient,
    },
    graph,
    "mm",
    input.requiredStrokeMm,
    { horizontalOffsetMm },
  );
}

export type MgpInterpolationResult =
  | { readonly inEnvelope: true; readonly loadMassKg: number }
  | MgpSelectionOutOfEnvelope;

export function interpolateMgpCurve(
  curve: MgpSelectionCurve,
  x: number,
): MgpInterpolationResult {
  if (!Number.isFinite(x) || curve.points.length < 2) {
    return outOfEnvelope(
      "invalid_input",
      "Curve interpolation requires a finite x value and at least two source points.",
    );
  }
  const first = curve.points[0]!;
  const last = curve.points[curve.points.length - 1]!;
  if (x < first.x || x > last.x) {
    return outOfEnvelope(
      "x_outside_curve_domain",
      `The query ${x} ${curve.xUnit} is outside this curve's seeded domain [${first.x}, ${last.x}].`,
    );
  }

  const exact = curve.points.find((point) => point.x === x);
  if (exact !== undefined) {
    return { inEnvelope: true, loadMassKg: exact.loadMassKg };
  }

  const upperIndex = curve.points.findIndex((point) => point.x > x);
  const lower = curve.points[upperIndex - 1]!;
  const upper = curve.points[upperIndex]!;
  if (curve.applicationCase === "stopper") {
    const ratio = (x - lower.x) / (upper.x - lower.x);
    return {
      inEnvelope: true,
      loadMassKg:
        lower.loadMassKg + ratio * (upper.loadMassKg - lower.loadMassKg),
    };
  }

  const ratio =
    (Math.log(x) - Math.log(lower.x)) / (Math.log(upper.x) - Math.log(lower.x));
  return {
    inEnvelope: true,
    loadMassKg: Math.exp(
      Math.log(lower.loadMassKg) +
        ratio * (Math.log(upper.loadMassKg) - Math.log(lower.loadMassKg)),
    ),
  };
}
